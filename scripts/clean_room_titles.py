#!/usr/bin/env python3
"""
One-off cleanup for KAN-6: remove markdown (e.g. '**') from existing room names.

Room titles generated by the AI were saved with markdown, so the dashboard showed
names like '**Healthcare Inequality: S...'. New titles are cleaned on save
(clean_ai_title); this script fixes rooms created before that.

Only rooms whose name contains markdown markers (*, `, __, or a leading '#') are
touched, so ordinary user-typed names are left alone.

Usage:
    python scripts/clean_room_titles.py           # dry run: shows what would change
    python scripts/clean_room_titles.py --apply   # actually updates the database
"""

import os
import re
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from src.app import create_app, db  # noqa: E402
from src.models import Room  # noqa: E402
from src.utils.title_generator import clean_ai_title  # noqa: E402

MARKDOWN = re.compile(r"\*|`|__|^\s*#")


def main(apply: bool) -> int:
    app = create_app()
    with app.app_context():
        changes = []
        for room in Room.query.order_by(Room.id).all():
            name = room.name or ""
            if not MARKDOWN.search(name):
                continue
            cleaned = clean_ai_title(name)
            if cleaned and cleaned != name:
                changes.append((room, name, cleaned))

        if not changes:
            print("No room names need cleaning.")
            return 0

        print(f"{len(changes)} room name(s) {'will be' if apply else 'would be'} changed:\n")
        for room, old, new in changes:
            print(f"  room {room.id}: {old!r}\n        -> {new!r}")

        if not apply:
            print("\nDry run only. Re-run with --apply to save these changes.")
            return 0

        for room, _old, new in changes:
            room.name = new
        db.session.commit()
        print(f"\nUpdated {len(changes)} room(s).")
        return 0


if __name__ == "__main__":
    sys.exit(main(apply="--apply" in sys.argv[1:]))
